"""Crystal symmetry engine built directly on spglib.

A symmetric crystal record stores the asymmetric unit together with the
*setting* it was reduced in:

* ``hall_number``: spglib Hall number (1-530), i.e. the space group *and* its
  standard setting (origin choice, axes, cell choice);
* ``setting_transformation`` ``P`` and ``origin_shift`` ``p``: spglib's
  transformation from the stored cell to that standard setting,
  ``x_std = P @ x + p``.

From these three values the symmetry operations are reconstructed in the basis
of the stored cell, so primitive cells, supercells, shifted origins and
non-standard settings all expand exactly. Nothing depends on a particular
library's default tables.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from typing import Any, Iterable, List, Optional, Sequence, Tuple

import numpy as np

from usif.exceptions import ValidationError

IDENTITY = np.eye(3)
ZERO = np.zeros(3)

#: Fractional tolerance used to merge symmetry-equivalent images of one point.
#: Images of a single site under exact operations coincide to ~1e-12, while
#: distinct atoms are separated by far more, so the value is not critical.
ORBIT_MERGE_TOLERANCE = 1e-5


def _spglib():
    try:
        import spglib
    except ImportError as exc:  # pragma: no cover - spglib is a core dependency
        raise ImportError("USIF symmetry support requires spglib: pip install spglib") from exc
    return spglib


@dataclass(frozen=True)
class CrystalSymmetry:
    """Result of analysing one crystal cell."""

    spacegroup: int
    hall_number: int
    international: str
    transformation: np.ndarray  # P, x_std = P x + p
    origin_shift: np.ndarray  # p
    equivalent_atoms: np.ndarray  # orbit representative index per atom
    wyckoffs: Tuple[str, ...]


def analyze_crystal(
    lattice: np.ndarray,
    frac_coords: np.ndarray,
    numbers: Sequence[int],
    *,
    symprec: float,
    angle_tolerance: float = -1.0,
) -> Optional[CrystalSymmetry]:
    """Return the spglib symmetry of a cell, or ``None`` if analysis fails."""
    spglib = _spglib()
    cell = (
        np.asarray(lattice, dtype=float),
        np.asarray(frac_coords, dtype=float),
        np.asarray(numbers, dtype=int),
    )
    dataset = spglib.get_symmetry_dataset(cell, symprec=symprec, angle_tolerance=angle_tolerance)
    if dataset is None:
        return None
    return CrystalSymmetry(
        spacegroup=int(dataset.number),
        hall_number=int(dataset.hall_number),
        international=str(dataset.international),
        transformation=np.array(dataset.transformation_matrix, dtype=float),
        origin_shift=np.array(dataset.origin_shift, dtype=float),
        equivalent_atoms=np.array(dataset.equivalent_atoms, dtype=int),
        wyckoffs=tuple(dataset.wyckoffs),
    )


def spacegroup_of_hall(hall_number: int) -> int:
    """Return the space-group number of a spglib Hall number."""
    if not 1 <= int(hall_number) <= 530:
        raise ValidationError(f"Hall number must be in 1..530, got {hall_number}")
    return int(_spglib().get_spacegroup_type(int(hall_number)).number)


def _wrap(values: np.ndarray) -> np.ndarray:
    wrapped = np.mod(values, 1.0)
    wrapped[np.isclose(wrapped, 1.0, atol=1e-12, rtol=0.0)] = 0.0
    return wrapped


def _lattice_translations(p_inv: np.ndarray) -> List[np.ndarray]:
    """Translations of the standard lattice expressed in the stored cell, mod 1.

    They are non-trivial when the stored cell is a supercell of the standard
    cell; the group they form is generated by the columns of ``P^-1``.
    """
    found = [ZERO.copy()]
    frontier = [ZERO.copy()]
    generators = [p_inv[:, i] for i in range(3)]
    while frontier:
        nxt = []
        for base in frontier:
            for gen in generators:
                cand = _wrap(base + gen)
                if not any(_close_periodic(cand, t) for t in found):
                    found.append(cand)
                    nxt.append(cand)
        frontier = nxt
        if len(found) > 100_000:  # pragma: no cover - absurd supercell
            raise ValidationError("setting transformation implies an unsupported supercell")
    return found


def _close_periodic(a: np.ndarray, b: np.ndarray, tol: float = ORBIT_MERGE_TOLERANCE) -> bool:
    diff = a - b
    diff -= np.round(diff)
    return bool(np.all(np.abs(diff) < tol))


@lru_cache(maxsize=1024)
def _operations_cached(
    hall_number: int, transformation: Tuple[float, ...], origin_shift: Tuple[float, ...]
) -> Tuple[np.ndarray, np.ndarray]:
    db = _spglib().get_symmetry_from_database(int(hall_number))
    if db is None:
        raise ValidationError(f"Unknown Hall number {hall_number}")
    rotations = np.asarray(db["rotations"], dtype=float)
    translations = np.asarray(db["translations"], dtype=float)

    P = np.array(transformation, dtype=float).reshape(3, 3)
    p = np.array(origin_shift, dtype=float)
    if abs(np.linalg.det(P)) < 1e-9:
        raise ValidationError("setting transformation matrix is singular")
    p_inv = np.linalg.inv(P)

    # In a supercell some operations of the crystal do not map the stored
    # lattice onto itself, so P^-1 R P is not integral. They are still exact
    # symmetries of the infinite crystal and map every site onto an image of an
    # atom, which is all orbit expansion needs, so they are kept as real
    # matrices (snapped to integers where they are integral).
    out_rot: List[np.ndarray] = []
    out_trans: List[np.ndarray] = []
    seen: List[Tuple[Tuple[float, ...], np.ndarray]] = []
    lattice_shifts = _lattice_translations(p_inv)
    for R, t in zip(rotations, translations):
        W = p_inv @ R @ P
        W_snapped = np.where(np.isclose(W, np.round(W), atol=1e-9), np.round(W), W)
        w = p_inv @ (R @ p + t - p)
        key = tuple(round(float(x), 9) for x in W_snapped.ravel())
        for shift in lattice_shifts:
            w_total = _wrap(w + shift)
            if any(k == key and _close_periodic(w_total, v) for k, v in seen):
                continue
            seen.append((key, w_total))
            out_rot.append(W_snapped)
            out_trans.append(w_total)
    rot_arr = np.array(out_rot, dtype=float)
    trans_arr = np.array(out_trans, dtype=float)
    rot_arr.setflags(write=False)
    trans_arr.setflags(write=False)
    return rot_arr, trans_arr


def setting_operations(
    hall_number: int,
    transformation: Optional[np.ndarray] = None,
    origin_shift: Optional[np.ndarray] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """Return ``(rotations, translations)`` acting on fractional coordinates of the stored cell."""
    P = IDENTITY if transformation is None else np.asarray(transformation, dtype=float)
    p = ZERO if origin_shift is None else np.asarray(origin_shift, dtype=float)
    return _operations_cached(
        int(hall_number),
        tuple(float(x) for x in P.ravel()),
        tuple(float(x) for x in p.ravel()),
    )


def xyz_tuple(values: Any) -> Tuple[float, float, float]:
    """Return a 3-vector as a tuple of Python floats."""
    x, y, z = (float(v) for v in values)
    return (x, y, z)


def expand_orbit(
    coords: Iterable[float],
    rotations: np.ndarray,
    translations: np.ndarray,
) -> np.ndarray:
    """Return the distinct images (wrapped to [0, 1)) of one fractional point."""
    x = np.asarray(tuple(coords), dtype=float)
    images = _wrap(np.einsum("nij,j->ni", np.asarray(rotations, dtype=float), x) + translations)
    unique: List[np.ndarray] = []
    for image in images:
        if not any(_close_periodic(image, u) for u in unique):
            unique.append(image)
    return np.array(unique)
